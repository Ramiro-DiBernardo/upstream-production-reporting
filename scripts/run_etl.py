"""Run the SQL ETL: raw CSVs -> SQLite -> staging -> validation -> marts -> CSVs for Power BI.

Run:  python scripts/run_etl.py
Outputs:
  data/mart/*.csv               tables loaded by the Power BI model
  docs/data_quality_report.md   summary of every validation check
"""
import csv
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW, MART, DOCS = ROOT / "data" / "raw", ROOT / "data" / "mart", ROOT / "docs"
DB = ROOT / "data" / "production.db"
MART.mkdir(parents=True, exist_ok=True)
DOCS.mkdir(exist_ok=True)

MARTS = {
    "mart_dim_well": "dim_well.csv",
    "mart_fact_daily": "fact_daily_production.csv",
    "mart_fact_downtime": "fact_downtime_events.csv",
    "mart_fact_loe": "fact_loe_monthly.csv",
    "mart_fact_sales_recon": "fact_sales_reconciliation.csv",
    "mart_fact_scada_hourly": "fact_scada_hourly.csv",
    "mart_dq_issues": "dq_issues.csv",
}


def load_raw(con):
    for f in sorted(RAW.glob("*.csv")):
        with open(f, newline="", encoding="utf-8") as fh:
            rows = list(csv.reader(fh))
        table = "raw_" + f.stem
        cols = ", ".join(f'"{c}" TEXT' for c in rows[0])
        con.execute(f'DROP TABLE IF EXISTS "{table}"')
        con.execute(f'CREATE TABLE "{table}" ({cols})')
        con.executemany(f'INSERT INTO "{table}" VALUES ({", ".join("?" * len(rows[0]))})', rows[1:])
        print(f"loaded {table:<26} {len(rows) - 1:>7,} rows")


def export(con):
    for table, name in MARTS.items():
        cur = con.execute(f"SELECT * FROM {table}")
        cols = [c[0] for c in cur.description]
        rows = cur.fetchall()
        with open(MART / name, "w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(cols)
            w.writerows(rows)
        print(f"exported {name:<30} {len(rows):>7,} rows")


def report(con):
    q = lambda sql: con.execute(sql).fetchall()
    raw_rows = q("SELECT COUNT(*) FROM raw_daily_production")[0][0]
    dups = q("SELECT COUNT(*) FROM stg_daily_production WHERE dup_rank > 1")[0][0]
    rejected = q("SELECT COUNT(*) FROM dq_issues WHERE severity = 'Error'")[0][0]
    clean = q("SELECT COUNT(*) FROM mart_fact_daily WHERE is_missing = 0")[0][0]
    spine = q("SELECT COUNT(*) FROM mart_fact_daily")[0][0]
    by_check = q("""SELECT check_name, severity, COUNT(*), MIN(action) FROM dq_issues
                    GROUP BY check_name, severity ORDER BY severity, COUNT(*) DESC""")
    recon = q("""SELECT month_start, lease, allocated_volume, sold_volume,
                        ROUND(100.0 * (sold_volume - allocated_volume) / allocated_volume, 1)
                 FROM mart_fact_sales_recon
                 WHERE product = 'Oil (bbl)' AND ABS(sold_volume - allocated_volume) / allocated_volume > 0.03
                 ORDER BY month_start""")
    lines = [
        "# Data quality report",
        "",
        "Generated by `scripts/run_etl.py` from the checks in [`sql/02_validation.sql`](../sql/02_validation.sql).",
        "",
        "## Row reconciliation (daily production)",
        "",
        "| Step | Rows |",
        "|---|---:|",
        f"| Raw rows received | {raw_rows:,} |",
        f"| − duplicate copies removed | {dups:,} |",
        f"| − rows rejected (negative / blank volume) | {rejected:,} |",
        f"| **= clean well-days loaded** | **{clean:,}** |",
        f"| Well-days expected (calendar spine) | {spine:,} |",
        f"| Well-days with no valid report | {spine - clean:,} |",
        "",
        f"Check: {raw_rows:,} − {dups:,} − {rejected:,} = {raw_rows - dups - rejected:,} "
        f"{'✅ matches' if raw_rows - dups - rejected == clean else '❌ does not match'} the clean row count.",
        "",
        "## Issues by check",
        "",
        "| Check | Severity | Issues | Action |",
        "|---|---|---:|---|",
    ]
    lines += [f"| {c} | {s} | {n:,} | {a} |" for c, s, n, a in by_check]
    lines += ["", "## Oil sales vs allocation, lease-months above 3%", "",
              "| Month | Lease | Allocated (bbl) | Sold (bbl) | Difference |", "|---|---|---:|---:|---:|"]
    lines += [f"| {m[:7]} | {l} | {a:,.0f} | {s:,.0f} | {p:+.1f}% |" for m, l, a, s, p in recon]
    (DOCS / "data_quality_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def main():
    if DB.exists():
        DB.unlink()
    con = sqlite3.connect(DB)
    load_raw(con)
    for f in sorted((ROOT / "sql").glob("*.sql")):
        con.executescript(f.read_text(encoding="utf-8"))
        print(f"ran {f.name}")
    con.commit()
    export(con)
    report(con)
    con.close()


if __name__ == "__main__":
    main()
